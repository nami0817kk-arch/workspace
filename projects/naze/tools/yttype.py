def stat(sel):
    xs = [r["x"] for r in sel]
    return (len(xs), st.median(xs), sum(x >= 3 for x in xs) / len(xs), sum(x >= 10 for x in xs) / len(xs), len({r["ch"] for r in sel}))
n, m, a, b, c = stat(rows); print(f"全体 {n}本 3倍↑{a:.0%} 10倍↑{b:.0%} {c}ch")
out = []
for k, p in T.items():
    sel = [r for r in rows if re.search(p, r["t"])]
    n, m, a, b, c = stat(sel)
    print(f"{k:<14} {n:>4}本 {c:>2}ch 倍率の真ん中 {m:.2f} 3倍↑{a:>4.0%} 10倍↑{b:>4.0%} 10万回↑{sum(r['n']>=100000 for r in sel)/n:>4.0%}")
