def FOC(name, on):
    return dict(k="focus", name=name, on=on)


def _steps(c):
    st = {}
    for f in c.seg["fx"]:
        if f["k"] == "step":
            w = c.when(f)
            st[f["n"]] = min(st.get(f["n"], w), w)
    return st


def _k(t, steps, n, dd=0.6):
    return sg.ease((t - steps.get(n, 1e9)) / dd)


def _font(a, b):
    return sg.F("YuGothB.ttc", b if P else a)


# ---- 図: 320 円の内訳(たとえの計算) ---------------------------------------------------------------------
SZ = [("材料など", 155, ORANGE), ("給料・家賃など", 156, BLUE), ("儲け", 9, YEL)]
SK = [("材料など", 107, ORANGE), ("給料・家賃など", 190, BLUE), ("儲け", 21, YEL)]


def draw_breakdown(img: Image.Image, t: float, c) -> None:
    """step 1 = 材料、step 2 = 給料・家賃、step 3 = 儲け(光り続ける)、step 4 = すかいらーくの棒を下に足す。"""
    import math
    st = _steps(c)
    bg = Image.new("RGBA", (W, H), BG)
    d = ImageDraw.Draw(bg, "RGBA")
    l, r = (W * 0.10, W * 0.90) if not P else (W * 0.06, W * 0.94)
    bh = H * (0.13 if not P else 0.065)
    y1 = H * (0.30 if not P else 0.24)
    y2 = y1 + bh * (2.6 if not P else 3.2)
    fL, fS, fT = _font(40, 44), _font(32, 36), _font(46, 52)
    sg.stext(d, (W / 2, y1 - bh * (1.25 if not P else 1.6)), "320円の内訳（会社全体の割合で計算）", fT, (230, 235, 245, 255), anchor="mm")

    def bar(y, name, parts, k_list, dim=1.0):
        sg.stext(d, (l, y - 34), name, fL, (230, 235, 245, int(255 * dim)), anchor="lm")
        d.rectangle([l, y, r, y + bh], outline=(90, 100, 120, 255), width=3)
        x = l
        for (lab, v, col), k in zip(parts, k_list):
            w = (r - l) * v / 320
            if k > 0:
                a = int(255 * dim)
                d.rectangle([x, y, x + w * k, y + bh], fill=col + (a,))
                if lab == "儲け":
                    pulse = 0.5 + 0.5 * math.sin(t * 4.0)
                    for rr in (10, 18, 26):
                        d.rectangle([x - rr * pulse, y - rr * pulse, x + w + rr * pulse, y + bh + rr * pulse], outline=YEL + (int(110 * k * (1 - rr / 30)),), width=3)
                    sg.stext(d, (x + w / 2, y + bh + (46 if not P else 52)), f"{lab} 約{v}円", fL, YEL + (int(255 * k),), anchor="rm" if not P else "rm")
                else:
                    sg.stext(d, (x + w / 2, y + bh / 2), f"{lab}", fS, (20, 24, 34, int(255 * k)), anchor="mm")
                    sg.stext(d, (x + w / 2, y + bh + (46 if not P else 52)), f"約{v}円", fL, col + (int(255 * k),), anchor="mm")
            x += w

    k1, k2, k3, k4 = _k(t, st, 1, 0.8), _k(t, st, 2, 0.8), _k(t, st, 3, 0.6), _k(t, st, 4, 0.8)
    bar(y1, "サイゼリヤ（日本）", SZ, [k1, k2, k3])
    if k4 > 0:
        bar(y2, "すかいらーく", SK, [k4, k4, k4], dim=0.85)
    # 何も足されない間も止めない: 枠の上を光の帯がゆっくり流れる
    u = ((t * 0.25) % 1.0)
    gx = l + (r - l) * u
    d.line([(gx, y1 - 6), (gx, y1 + bh + 6)], fill=(255, 255, 255, 70), width=6)
    sg.stext(d, (W - 40, H * (0.86 if not P else 0.60)), "たとえの計算", _font(30, 36), (120, 130, 150, 255), anchor="rm")
    img.alpha_composite(bg)


# ---- 図: 産地から店まで(製造直販) -----------------------------------------------------------------------
def draw_flow(img: Image.Image, t: float, c) -> None:
    """step 1 = 産地→工場→店を矢印でつなぐ(上に「サイゼリヤが自分で」)、step 2 = 間の「問屋」に×。矢印の上を点が流れ続ける。"""
    st = _steps(c)
    bg = Image.new("RGBA", (W, H), BG)
    d = ImageDraw.Draw(bg, "RGBA")
    k1, k2 = _k(t, st, 1, 0.8), _k(t, st, 2, 0.8)
    f, fS = _font(48, 54), _font(34, 40)
    if not P:
        xs = [W * 0.17, W * 0.50, W * 0.83]
        ys = [H * 0.46] * 3
    else:
        xs = [W * 0.5] * 3
        ys = [H * 0.16, H * 0.34, H * 0.52]
    names = ["産地", "自社工場", "店"]
    subs = ["牛・牛乳・レタス", "ソース・炊飯・小分け", "すぐ使える形で届く"]
    bw, bh = (W * 0.20, H * 0.16) if not P else (W * 0.56, H * 0.10)
    for i in range(3):
        a = int(255 * k1)
        x, y = xs[i], ys[i]
        d.rounded_rectangle([x - bw / 2, y - bh / 2, x + bw / 2, y + bh / 2], radius=18, fill=(34, 44, 66, a), outline=ORANGE + (a,), width=4)
        sg.stext(d, (x, y - bh * 0.12), names[i], f, (240, 240, 245, a), anchor="mm")
        sg.stext(d, (x, y + bh * 0.26), subs[i], fS, (180, 190, 205, a), anchor="mm")
    for i in range(2):
        a = int(255 * k1)
        if not P:
            p0, p1 = (xs[i] + bw / 2 + 10, ys[i]), (xs[i + 1] - bw / 2 - 10, ys[i])
        else:
            p0, p1 = (xs[i], ys[i] + bh / 2 + 8), (xs[i], ys[i + 1] - bh / 2 - 8)
        d.line([p0, p1], fill=ORANGE + (a,), width=6)
        if k1 >= 1:
            for j in range(3):
                u = ((t * 0.6) + j / 3) % 1.0
                px, py = p0[0] + (p1[0] - p0[0]) * u, p0[1] + (p1[1] - p0[1]) * u
                d.ellipse([px - 9, py - 9, px + 9, py + 9], fill=(255, 230, 160, 230))
    if k1 > 0:
        top = (W / 2, H * 0.24) if not P else (W / 2, H * 0.075)
        sg.stext(d, top, "ぜんぶサイゼリヤが自分で", _font(52, 56), ORANGE + (int(255 * k1),), anchor="mm")
    if k2 > 0:
        a = int(255 * k2)
        mx, my = ((xs[0] + xs[1]) / 2, ys[0] + bh * 0.95) if not P else (W * 0.80, (ys[0] + ys[1]) / 2)
        ww, hh = (W * 0.12, H * 0.09) if not P else (W * 0.22, H * 0.05)
        d.rounded_rectangle([mx - ww / 2, my - hh / 2, mx + ww / 2, my + hh / 2], radius=12, fill=(50, 54, 64, a), outline=GREY + (a,), width=3)
        sg.stext(d, (mx, my), "問屋", f, GREY + (a,), anchor="mm")
        d.line([(mx - ww * 0.6, my - hh * 0.7), (mx + ww * 0.6, my + hh * 0.7)], fill=(235, 70, 70, a), width=10)
        d.line([(mx - ww * 0.6, my + hh * 0.7), (mx + ww * 0.6, my - hh * 0.7)], fill=(235, 70, 70, a), width=10)
        sg.stext(d, (mx, my + hh * (1.0 if not P else 0.95)), "はさまない", fS, (235, 120, 120, a), anchor="mm")
    sg.stext(d, (W - 40, H * (0.86 if not P else 0.60)), "公式サイトの説明から作図", _font(30, 36), (120, 130, 150, 255), anchor="rm")
    img.alpha_composite(bg)


