def S(name):
    return f"assets/stock/{name}"


def V(name, start=0.0, speed=1.0, cx=0.5, place=None, **kw):
    d = dict(kind="video", src=S(name + ".mp4"), start=start, speed=speed, cx=cx, **kw)
