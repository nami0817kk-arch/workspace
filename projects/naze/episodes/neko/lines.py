def _steps(c):
    st = {}
    for f in c.seg["fx"]:
        if f["k"] == "step":
            w = c.when(f)
            st[f["n"]] = min(st.get(f["n"], w), w)
    return st


def _k(t, steps, n, dd=0.6):
    return sg.ease((t - steps.get(n, 1e9)) / dd)


def _font(a, b):
    return sg.F("YuGothB.ttc", b if P else a)


# ---- 図: 体を前と後ろに分けてひねる(模式図) --------------------------------------------------------------
def draw_twist(img: Image.Image, t: float, c) -> None:
    """猫を前(上半身)と後ろ(下半身)の 2 つの楕円で描く。step 1 = 前が 180° 回る(後ろは少し逆へ)、step 2 = 後ろが回る。"""
    import math
    st = _steps(c)
    bg = Image.new("RGBA", (W, H), BG)
    d = ImageDraw.Draw(bg, "RGBA")
    cx, cy = W / 2, H * (0.45 if not P else 0.38)
    seg = W * (0.17 if not P else 0.26)
    k1, k2 = _k(t, st, 1, 1.2), _k(t, st, 2, 1.2)
    a_front = 180 * k1
    a_back = -25 * k1 * (1 - k2) + 180 * k2
    f = _font(40, 46)
    for name, x, ang, col in (("前（上半身）", cx - seg * 0.55, a_front, (255, 200, 90)), ("後ろ（下半身）", cx + seg * 0.55, a_back, (150, 210, 255))):
        rx, ry = seg * 0.55, seg * 0.36 * abs(math.cos(math.radians(ang))) + seg * 0.08
        d.ellipse([x - rx, cy - ry, x + rx, cy + ry], fill=col + (230,))
        up = math.cos(math.radians(ang)) >= 0       # 足の向き(背中が下の間は上、回り切ると下)
        for dx in (-0.25, 0.25):
            fx = x + rx * dx
            y0 = cy + (ry if not up else -ry)
            y1 = y0 + (seg * 0.35 if not up else -seg * 0.35)
            d.line([(fx, y0), (fx, y1)], fill=col + (255,), width=14)
        sg.stext(d, (x, cy + seg * 1.0), name, f, col + (255,), anchor="mm")
    lab = "背中が下" if k1 < 0.5 else ("前が回った" if k2 < 0.5 else "足が下に")
    sg.stext(d, (cx, cy - seg * 0.85), lab, _font(48, 54), (255, 255, 255, 255), anchor="mm")
    sg.stext(d, (W - 40, H * (0.86 if not P else 0.60)), "模式図", _font(30, 36), (120, 130, 150, 255), anchor="rm")
    img.alpha_composite(bg)


# ---- 図: ニューヨークの記録の形(高さとけが。模式図) -----------------------------------------------------
def draw_nycurve(img: Image.Image, t: float, c) -> None:
    """step 1 = 2〜7 階で上がる線、step 2 = 7 階より上で下がる線。"""
    st = _steps(c)
    bg = Image.new("RGBA", (W, H), BG)
    d = ImageDraw.Draw(bg, "RGBA")
    l, r = (W * 0.14, W * 0.86) if not P else (W * 0.12, W * 0.90)
    top, bot = (H * 0.20, H * 0.74) if not P else (H * 0.22, H * 0.58)
    fS = _font(32, 38)
    d.line([(l, bot), (r, bot)], fill=(170, 180, 200, 255), width=3)
    d.line([(l, top), (l, bot)], fill=(170, 180, 200, 255), width=3)

    def X(fl):
        return l + (fl - 2) / 30 * (r - l)

    def Y(v):
        return bot - v * (bot - top)
    for fl in (2, 7, 15, 25, 32):
        sg.stext(d, (X(fl), bot + 30), f"{fl}階", fS, (170, 180, 200, 255), anchor="mm")
    sg.stext(d, (l + 10, top - 30), "けがの多さ", fS, (170, 180, 200, 255), anchor="lm")
    k1, k2 = _k(t, st, 1, 1.0), _k(t, st, 2, 1.2)
    if k1 > 0:
        x1 = 2 + 5 * k1
        d.line([(X(2), Y(0.25)), (X(x1), Y(0.25 + 0.6 * (x1 - 2) / 5))], fill=(255, 140, 90, 255), width=8)
    if k2 > 0:
        x2 = 7 + 25 * k2
        d.line([(X(7), Y(0.85)), (X(x2), Y(0.85 - 0.45 * (x2 - 7) / 25))], fill=(255, 214, 64, 255), width=8)
    sg.stext(d, (r, bot + 70), "模式図（形だけを示す）", fS, (120, 130, 150, 255), anchor="rm")
    img.alpha_composite(bg)


# ---- 図: 記録の穴(10 匹落ちて、病院に来たのは 1 匹) -------------------------------------------------------
def draw_bias(img: Image.Image, t: float, c) -> None:
    """step 1 = 10 匹の丸、step 2 = 9 匹が灰色に消える(その場で助からず、病院に来ない)、step 3 = 残った 1 匹に「記録: 軽いけが」。"""
    st = _steps(c)
    bg = Image.new("RGBA", (W, H), BG)
    d = ImageDraw.Draw(bg, "RGBA")
    n = 10
    r = W * (0.03 if not P else 0.045)
    y = H * (0.42 if not P else 0.36)
    gap = (W * (0.70 if not P else 0.84)) / (n - 1)
    x0 = W / 2 - gap * (n - 1) / 2
    k1, k2, k3 = _k(t, st, 1), _k(t, st, 2, 1.0), _k(t, st, 3)
    for i in range(n):
        if k1 <= 0:
            break
        x = x0 + gap * i
        keep = i == 6
        col = (255, 200, 90) if keep else (int(255 - 175 * k2), int(200 - 120 * k2), int(90 - 10 * k2))
        a = 255 if keep else int(255 * (1 - 0.65 * k2))
        d.ellipse([x - r, y - r, x + r, y + r], fill=col + (int(a * k1),))
    f = _font(40, 46)
    sg.stext(d, (W / 2, y - r - 70), "32階から落ちた猫（たとえば10匹）", f, (220, 225, 235, int(255 * k1)), anchor="mm")
    if k2 > 0:
        sg.stext(d, (W / 2, y + r + 60), "その場で助からず、病院に来ない", f, (150, 155, 165, int(255 * k2)), anchor="mm")
    if k3 > 0:
        sg.stext(d, (W / 2, y + r + 140), "記録：1匹、軽いけが", _font(54, 60), (255, 214, 64, int(255 * k3)), anchor="mm")
    sg.stext(d, (W - 40, H * (0.86 if not P else 0.60)), "たとえの図", _font(30, 36), (120, 130, 150, 255), anchor="rm")
    img.alpha_composite(bg)


