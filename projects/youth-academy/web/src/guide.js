    const [label, act] = g.go;
    return h('button', { class: 'btn sm sgo', onclick: () => {
      const app = U().app;
      if (typeof act === 'function') { act(app); U().render(); return; }
      const el = document.querySelector(act);
      if (el && el.scrollIntoView) el.scrollIntoView({ block: 'start' });
    } }, label);
