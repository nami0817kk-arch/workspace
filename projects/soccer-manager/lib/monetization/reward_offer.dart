/// リワード広告を1本見る、またはサポーター購入によって受け取れる特典。
///
/// 特典を「資金」に絞っているのは、このゲームのバランスを10ラウンドかけて
/// 実測調整してきたため。成長率や試合の勝率に直接触る特典を用意すると、
/// その調整が意味を失う。資金なら、選手を買うか施設に回すかの判断は
/// プレイヤーに残るし、既にデバッグ用の資金追加機能が存在していて
/// 経済に穴を空けない範囲の額は把握できている。
///
/// 対戦相手のいない単独プレイのゲームなので、他人の体験を害することもない。
class RewardOffer {
  const RewardOffer._();

  /// 1回あたりの資金(万円)。所属ディビジョンに比例させる。
  ///
  /// 下部リーグでは少額でも効くが、1部で同じ額を配っても意味がない。
  /// 逆に1部の額を5部で配ると序盤の経営判断が消し飛ぶ。
  /// tier は1(最上位)〜5(最下位)。
  static int fundsFor(int divisionTier) {
    const byTier = {1: 1000, 2: 700, 3: 500, 4: 350, 5: 250};
    return byTier[divisionTier] ?? 250;
  }

  /// 1日に受け取れる上限。
  ///
  /// 際限なく配ると経営シミュレーションとして成立しなくなる。
  /// 無料で1日3回まで。
  static const int dailyLimitFree = 3;

  /// サポーター購入者の1日あたりの上限。
  ///
  /// 「広告を消す」だけの購入にすると、広告が任意視聴である以上
  /// 買っても何も変わらない。広告を見ずに同じ特典を受け取れて、
  /// 回数もやや多い、という形にしている。
  static const int dailyLimitSupporter = 5;
}
