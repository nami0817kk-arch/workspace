"""標準時間と必要人員の計算。"""
from ._spec import Affiliate, Faq, Field, Output, Tool

ASP = "※ リンク先は提携先のサイトです。導入前に自社の要件をご確認ください。"

TOOL = Tool(
    slug="standard-time",
    title="標準時間・必要人員 計算ツール",
    description="正味時間と余裕率から標準時間を出し、就業時間あたりの生産可能数と、必要生産数に対する必要人員を計算します。",
    category="生産管理",
    lead="ストップウォッチで測った正味時間だけで計画を立てると必ず足りなくなります。"
         "余裕率を加えた標準時間で見ると、1日に何個作れて、何人必要かが出ます。",
    updated="2026-08-29",
    keywords=["標準時間 計算", "余裕率 計算", "必要人員 計算", "標準時間 求め方"],
    inputs=[
        Field("net_sec", "正味時間", unit="秒/個", default=90, min=0,
              hint="実際に作業している時間。測定値の中央値が実務的です"),
        Field("rating", "レイティング係数", unit="%", default=100, min=1,
              hint="測定した作業者の速さ。標準的なら100、速い人なら110など"),
        Field("allowance", "余裕率", unit="%", default=20, min=0,
              hint="用便・疲労・段取り・不定期作業の合計。15〜25%が一般的"),
        Field("work_min", "1日の就業時間", unit="分", default=450, min=1,
              hint="休憩を除いた実働時間"),
        Field("required_qty", "1日に必要な生産数", unit="個", default=300, min=0),
    ],
    outputs=[
        Output("standard_sec", "標準時間",
               "net_sec * (rating / 100) * (1 + allowance / 100)",
               unit="秒/個", decimals=1, primary=True,
               note="計画に使うべき1個あたりの時間"),
        Output("per_person", "1人あたりの1日生産可能数",
               "work_min * 60 / (net_sec * (rating / 100) * (1 + allowance / 100))",
               unit="個/日", decimals=0),
        Output("people", "必要人員",
               "required_qty / (work_min * 60 / "
               "(net_sec * (rating / 100) * (1 + allowance / 100)))",
               unit="人", decimals=2,
               note="端数は切り上げて配置します"),
        Output("takt_sec", "タクトタイム", "work_min * 60 / required_qty",
               unit="秒/個", decimals=1,
               note="必要数を作るために許される1個あたりの時間"),
        Output("allowance_sec", "余裕時間の内訳",
               "net_sec * (rating / 100) * (allowance / 100)",
               unit="秒/個", decimals=1),
    ],
    formula_note="""標準時間 ＝ 正味時間 × レイティング係数 × (1 + 余裕率)
1人あたり生産可能数 ＝ 就業時間 ÷ 標準時間
必要人員 ＝ 必要生産数 ÷ 1人あたり生産可能数
タクトタイム ＝ 就業時間 ÷ 必要生産数

標準時間がタクトタイムを上回っていると、その工程では必要数を作れません。
その場合は人を増やすか、工程を分けるか、標準時間そのものを縮める必要があります。""",
    steps=[
        "作業を10回以上測定し、正味時間の中央値を入れます。極端に速い回・遅い回は除きます。",
        "測定した作業者の速さをレイティング係数で補正します。標準的な人なら100のままで構いません。",
        "余裕率を入れます。分からなければ20%から始め、実績とのずれを見て調整します。",
        "就業時間と必要生産数を入れると、必要人員とタクトタイムが出ます。",
        "標準時間がタクトタイムを超えていないか確認します。超えていればその工程がボトルネックです。",
    ],
    faq=[
        Faq("余裕率はどう決めますか",
            "用便・疲労などの人的余裕と、段取り・打ち合わせなどの管理余裕を分けて積み上げるのが本来です。"
            "実務では15〜25%が一つの目安ですが、自社の実績（計画と実績の乖離）から逆算するのが確実です。"),
        Faq("レイティング係数が分かりません",
            "100のままでも構いません。同じ人の測定値を継続して使う限り、"
            "係数は一定なので比較には支障がありません。"
            "複数人の測定値を混ぜる場合に補正が必要になります。"),
        Faq("必要人員が小数になります",
            "切り上げて配置するのが基本です。ただし1.2人のような値が出た場合は、"
            "工程の組み替えや多能工化で1人に収まらないかを先に検討してください。"),
        Faq("標準時間とタクトタイムの違いは",
            "標準時間は「1個作るのにかかる時間」、タクトタイムは「1個作ることを許される時間」です。"
            "前者が後者を超えると必要数に届きません。"),
    ],
    affiliate=Affiliate(
        heading="工数の実績を自動で集める",
        body="標準時間は一度決めて終わりではなく、実績と突き合わせて更新するものです。"
             "工数管理・勤怠システムで作業実績を自動収集すると、"
             "計画と実績の乖離が見えて余裕率の妥当性を検証できます。",
        cta="工数・勤怠管理システムを比較する",
        url="https://example.com/",
        note=ASP,
    ),
)
