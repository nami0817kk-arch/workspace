/// 手書きの最期: 忍び・流れ者・野盗（90本）。
/// 里に残った忍び・抜け忍・流れ者・野盗・足を洗った者を、死に方8種と乱世の終わり（era）で書き分ける。
/// この道に入るのは、身分を得なかった（maxRank 0）人生だけ（`lifeWay`）。

int _a(Game g) => g.age;
bool _dead(Game g, String s) => (g.l.dead ?? '').contains(s);
bool _f(Game g, String f) => g.hasFlag(f);
bool _path(Game g, String s) => g.l.path.any((p) => p.contains(s));
bool _ninja(Game g) => g.l.cls.id == 'ninja';

/// 里に残った忍び（抜けず、野にも出ていない）。
bool _sato(Game g) =>
    _ninja(g) &&
    !_f(g, 'nukenin') &&
    !_f(g, 'way_outlaw') &&
    !_f(g, 'wanderer');
bool _nuke(Game g) => _f(g, 'nukenin');
bool _wand(Game g) => _f(g, 'wanderer');

/// 野盗（流れ者でも抜け忍でもなく、野に生きる者）。
bool _bandit(Game g) => _f(g, 'way_outlaw') && !_wand(g) && !_nuke(g);
bool _ref(Game g) => _f(g, 'reformed');
bool _head(Game g) => g.l.people.containsKey('頭');

