/// 子どものころ、どの国にいても届いた大きな出来事の噂（5〜14歳）。
/// 国ごとの史実の岐路（`h_c_`）がその年にあれば、そちらが先に出る（幼少期の岐路は1年に1つ）。

SceneDef _rumor(
  String id,
  int year,
  String title,
  String text,
  String listen,
  String memory,
) {
  return SceneDef('h_r_$id', 5, 14, (g) => 20, (g) => true, (g, next) {
    g.ask(title, text, [
      Choice.h('大人たちの話に聞き入る', '世の中のことが、少し分かるようになる', () {
        g.l.chi = clampInt(g.l.chi + 1, 0, 99);
        g.mark(memory);
        return listen;
      }),
      Choice.h('遊びに戻る', '子どもには、遠い国の話だ', () {
        g.j(2);
        return '遠い国の話より、今日の遊びの方が大事だった。';
      }),
    ], after: next);
  }, ageOk: (g, a) => g.l.startYear + a == year);
}

