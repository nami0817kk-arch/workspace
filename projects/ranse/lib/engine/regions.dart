/// 国ごとの暮らしの岐路（2026-11-23）。
///
/// 史実の岐路（`history_east.dart`・`history_west.dart`）は国ごとにあるが、史実でない日々の暮らしの出来事は
/// どの国でもほぼ同じで、生まれ直しても土地の手触りが変わらなかった。22国それぞれの風土・産物・習わしにちなむ岐路を置く。
/// id・旗は `rg_`（子どもは `rg_c_`）。どれも一生に一度、重み2〜4。条件は今いる国（`l.region`）で見る。

bool _in(Game g, String r) => g.l.region == r;
bool _monk(Game g) => g.hasFlag('priesthood');
bool _outlaw(Game g) => g.hasFlag('way_outlaw');
/// 身分のない暮らし（仏門・野の道を除く。商人は含む）。
bool _commoner(Game g) =>
    g.l.rank == 0 && g.active && !_monk(g) && !_outlaw(g);

/// 主家に仕える侍（戦える人）。
bool _samurai(Game g) =>
    g.l.rank >= 1 &&
    g.l.rank <= 7 &&
    g.active &&
    !_monk(g) &&
    g.l.lord != null &&
    (g.fa[g.l.lord]?.alive ?? false) &&
    g.canFight;

/// 国の主でなく、隠居も野の道もしていない人（仏門は含む）。
bool _folk(Game g) => g.active && !_outlaw(g) && g.l.rank < 8;

/// 武家の子（男）。
bool _bukeBoy(Game g) =>
    !g.l.female &&
    const [
      'ashigaru',
      'lowsamurai',
      'samurai',
      'kokujin',
      'ronin',
    ].contains(g.l.cls.id);

void _pay(Game g, int n) => g.l.gold = g.l.gold >= n ? g.l.gold - n : 0;
void _heal(Game g, int n) =>
    g.l.hp = g.l.hp + n > g.l.maxhp ? g.l.maxhp : g.l.hp + n;
void _net(Game g, int n) => g.l.net = g.l.net + n < 0 ? 0 : g.l.net + n;

