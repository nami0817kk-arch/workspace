/// 特性の効く場面 その3（2026-11-24、特性100の3回目）。`trait_scenes.dart` の続き（表 [kTraitScenesDone] は一つ）。
///
/// 3回目で効き方を作った25:
/// - よくある10（一生に一度の出来事）: 健脚・大柄・小柄・頑固・楽天家・心配性・物好き・親孝行・辛抱強い・生き物に好かれる。
///   心配性は凶作の冬に飢えにくく（[traitHunger]）、辛抱強いは籠城で飢えにくい（[traitSiege]）。
/// - 珍しい8（既存の仕組みに掛ける＋場面一つ）: 地獄耳（刺客）・船に強い（仕入れの船）・沈着（大水と大地震）・
///   気前がいい（給金が払えない年の兵）・歌詠み（連歌の会）・茶の心（茶の湯）・寺に縁者（主君の怒りに寺へ駆け込む手）・
///   没落した名家の出（仕官）。
/// - 稀5（筋）: 星を読む・鍛冶の血・笛の名手・神仏の申し子・神隠しの子。
/// - 幻2（一生の筋）: 忌み子・狐の子。
///
/// 2回目の気がかり「城主より上の人にも村の書き出しが出うる」を避けるため、3回目の場面は身分で書き分ける
/// （[_by]: 城主より上＝[_high]・主家に仕える身・それ以外）。泰平の世（[_pz]）では陣中の書き出しを出さず、
/// 健脚・大柄・物好き・歌詠み・茶の心・星を読む・鍛冶の血・笛の名手・狐の子は泰平だけの書き出しや手を持つ。

/// 城主より上（位5〜8。隠居した人は最高位で見る）。奥で仕える女性は位が高くても「主家に仕える身」の書き出しにする。
bool _high(Game g) => g.canFight && (g.l.rank >= 5 || (!g.active && g.l.maxRank >= 5));

/// 江戸に幕府のある世か（史実どおりの世で、小田原の分岐が起きていない）。
bool _edoWorld(Game g) => worldLine(g) == 'real' && !g.hasFlag('history_odawara');

/// 泰平の世の、天下の政の置かれた町（小田原の分岐の世では駿府、歴史が変わった世では上方）。
String _seat(Game g) =>
    _edoWorld(g) ? '江戸' : (worldLine(g) == 'real' ? '駿府' : '上方');

/// 身分で書き分ける: 城主より上・主家に仕える身・それ以外（村や町の者・商い・野・仏門）。
T _by<T>(Game g, T high, T serving, T common) =>
    _high(g) ? high : (_serving(g) ? serving : common);

// ---------------------------------------------------------------- 既存の仕組みに掛ける倍率（3回目）

/// 凶作の冬に飢える危うさの倍率（3回目の分。心配性は備えがある。[traitHunger] が掛ける）。
double _hunger3(Game g) => g.has('worrier') ? .6 : 1;

/// 籠城で飢える危うさの倍率（辛抱強い。`ways.dart` の籠城）。
double traitSiege(Game g) => g.has('patient') ? .6 : 1;

/// 刺客に討たれる危うさの倍率（地獄耳。`ways.dart` の刺客の影）。
double traitAssassin(Game g) => g.has('keen_ear') ? .5 : 1;

/// 仕入れの船が嵐に呑まれる危うさの倍率（船に強い。`ways.dart` の仕入れの旅）。
double traitSeaRisk(Game g) => g.has('sea_legs') ? .5 : 1;

/// 大水・大地震で命を落とす危うさの倍率（沈着。`ways.dart`）。
double traitDisaster(Game g) => g.has('calm') ? .5 : 1;

/// 給金が払えない年にも、兵が逃げないか（気前がいい。`game.dart` の暮らし）。
bool traitKeepsMen(Game g) => g.has('generous');

/// 連歌の会で名が上がる見込みに足す値（歌詠み。`pastimes.dart`）。
double traitRenga(Game g) => g.has('poet') ? .4 : 0;

/// 茶の湯の稽古で人の輪に足す値（茶の心。`pastimes.dart`）。
int traitTea(Game g) => g.has('tea') ? 1 : 0;

/// 仕官の見込みに足す値（没落した名家の出。`adult.dart` の仕官）。
double traitServeEdge(Game g) => g.has('fallen') ? .08 : 0;

/// 主君に腹を切れと命じられたとき、叔父の寺へ駆け込めるか（寺に縁者。`ways.dart` の主君の怒り）。
bool traitTempleRefuge(Game g) => g.has('temple_kin');

/// 叔父の寺へ駆け込んで髪を下ろす（`ways.dart` の主君の怒りの手）。
String templeRefuge(Game g) {
  final l = g.l;
  g.setFlag('priesthood');
  g.setFlag('tr_temple_kin_refuge');
  l.rank = 0;
  l.lord = null;
  l.troops = 0;
  l.ronin = false;
  l.flags.remove('way_outlaw');
  l.flags.remove('way_merchant');
  g.j(-4);
  g.mark('主君の怒りを逃れて叔父の寺の門をくぐり、その日のうちに髪を剃った');
  return '夜道を駆けて、叔父の寺の門を叩いた。叔父は何も聞かずに剃刀を取った。追っ手は山門の前まで来たが、寺の内へは踏み込まなかった。';
}

