/// 手書きの最期: 城主・家老（150本）。
/// 最高位が5〜7（城主・家老・宿老）まで上った男の最期を、
/// 城下の切り盛り（町割り・年貢・治水・検地・兵糧）、家臣（牢人・軍師・若侍・老臣・寵臣）、
/// 家族（嫡男・娘・妻・人質の子）、主家との間合い（密書・寝返り・下剋上の下地・国替え）、
/// 史実の合戦と有名人の主君で書き分ける。
/// 地位と幸福の食い違い（一城を守り抜いたが家族を失った／出世より領民を選んだ）も拾う。

int _a(Game g) => g.age;
bool _f(Game g, String f) => g.hasFlag(f);
bool _dead(Game g, String s) => (g.l.dead ?? '').contains(s);
bool _p(Game g, String s) => g.l.path.any((x) => x.contains(s));
bool _has(Game g, String role) => g.l.people.containsKey(role);
int _bond(Game g, String role) => g.l.people[role]?.bond ?? 0;
bool _in(Game g, List<String> rs) => rs.contains(g.l.region);
int _mr(Game g) => g.l.maxRank;

/// 主君として仕えた名のある人（いれば）。
String _master(Game g) => g.l.people['主君']?.name ?? '';

/// 隠居した。
bool _ret(Game g) => _f(g, 'retired');

/// 位を失った（牢人・降格）。隠居は含めない。
bool _fallen(Game g) => g.l.rank < 5 && !_ret(g);

/// いまも城を預かる身。
bool _inOffice(Game g) => g.l.rank >= 5 && !_ret(g);

