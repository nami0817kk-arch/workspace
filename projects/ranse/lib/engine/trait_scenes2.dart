/// 一六〇一年からの、戦の絶えた世。
bool _pz(Game g) => g.year >= kPeaceFrom && peaceTime(g);

/// 戦に出る身で、まだ戦のある世（陣中の書き出しを使うか）。
bool _war(Game g) => _fighter(g) && !_pz(g);

// ---------------------------------------------------------------- 既存の仕組みに掛ける倍率（2回目）

/// 合戦の討死の危うさの倍率（2回目の分。[traitBattleRisk] が掛ける）。
double _battleRisk2(Game g, String role) {
  var m = 1.0;
  if (g.has('painless')) m *= .9;
  if (g.has('tactics')) m *= .95;
  if (g.has('deathless')) m *= .75;
  if (g.has('kensei')) m *= .85;
  return m;
}

/// 合戦の手柄の倍率（2回目の分。[traitBattleGain] が掛ける）。
double _battleGain2(Game g, String role) {
  var m = 1.0;
  if (g.has('brave') && role == 'van') m *= 1.12;
  if (g.has('tactics')) m *= 1.06;
  if (g.has('archer') && role != 'van') m *= 1.12;
  if (g.has('general') && g.l.rank >= 2) m *= 1.1;
  if (g.has('kensei')) m *= 1.1;
  return m;
}

/// 老いの坂の倍率（長命の血筋。`game.dart` の天寿の見立てに掛ける）。
double traitOldAge(Game g) => g.has('longlived') && g.age >= 50 ? .8 : 1;

/// 凶作の冬に飢える危うさの倍率（鉄の胃袋。`adult.dart` の凶作）。
double traitHunger(Game g) => (g.has('iron_gut') ? .4 : 1) * _hunger3(g);

/// 仕入れの旅で当たる見込みに足す値（堺に親類。`ways.dart`）。
double traitTradeEdge(Game g) => (g.has('sakai_kin') ? .1 : 0) + _tradeEdge4(g);

