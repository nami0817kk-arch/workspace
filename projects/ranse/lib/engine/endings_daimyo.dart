/// 手書きの最期: 大名・下剋上（180本）。
/// 最高位が8（一国の主）になった男の最期。生まれながらの大名・下剋上で主家を乗っ取った者・
/// 国を失った元大名・隠居した元国主を、死に方（天寿・病・戦死・暗殺・切腹・災い・飢え・行方知れず・
/// 乱世を生き抜いた）と、大名の岐路の旗（分国法・楽市・名城・人質・弟の謀反・旧友の内通・世継ぎ・
/// 天下に手が届いた者の選び）・生まれの身分・世界線で書き分ける。
/// 女性の大名は女の道、天下統一した者は天下人なので、ここには男だけが来る。

int _a(Game g) => g.age;
String _c(Game g) => g.l.cls.id;
bool _f(Game g, String f) => g.hasFlag(f);
bool _dead(Game g, String s) => (g.l.dead ?? '').contains(s);
bool _p(Game g, String s) => g.l.path.any((x) => x.contains(s));
bool _in(Game g, List<String> rs) => rs.contains(g.l.region);
bool _has(Game g, String role) => g.l.people.containsKey(role);

/// 主家を討って国を取った者。
bool _geko(Game g) => _p(g, '主家を討ち');

/// 生まれながらの大名の家の者。
bool _born(Game g) => _c(g) == 'daimyo';

/// 百姓の子から下剋上で一国の主になった者。
bool _farmUp(Game g) => _geko(g) && _c(g) == 'farmer';

/// 国を失った元大名（隠居は位を保つので、位が8を下回るのは国が滅んだときだけ）。
bool _fallen(Game g) => g.l.rank < 8;

/// 天下に手が届きかけた者。
bool _big(Game g) => g.share >= .3;

bool _married(Game g) => g.l.married && _has(g, '伴侶');

