/// 手書きの最期: 仏門（80本）。
/// 出家した僧・尼（`priesthood` の旗）の最期を、男は僧、女は尼として書き分ける。
/// 天寿（入寂）・病・戦死（一揆・比叡山・石山）・災い（焼き討ちの炎・地震）・行方知れず（遊行）・
/// 処刑（キリシタン・慈悲の咎）・暗殺・飢え・乱世を生き抜いた（era）を、
/// 出家の経緯（師のもとで・夫を亡くして・晩年に・寺に預けられた子）・住持・遊行・弟子・史実で分ける。

int _a(Game g) => g.age;
bool _fe(Game g) => g.l.female;
bool _f(Game g, String f) => g.hasFlag(f);
bool _dead(Game g, String s) => (g.l.dead ?? '').contains(s);
bool _p(Game g, String s) => g.l.path.any((x) => x.contains(s));
bool _in(Game g, List<String> rs) => rs.contains(g.l.region);
bool _has(Game g, String role) => g.l.people.containsKey(role);

/// 夫を亡くして尼になった人。
bool _widow(Game g) => _fe(g) && _p(g, '尼となった');

/// 師のもとで出家した人。
bool _byMaster(Game g) => _p(g, 'のもとで出家し');

/// 晩年に世を捨てて出家した人。
bool _late(Game g) => _p(g, '世を捨て、髪を下ろした');

