/// 中央と西国（尾張・美濃・近江・山城・摂津・越前・安芸・出雲・土佐・薩摩・豊後・肥前）の史実の岐路。
///
/// 家臣には合戦と籠城を、庶民には暮らしに届く出来事と有名人との出会いを用意する。
/// どれも史実の年にだけ出る（`ageOk`）。id は `h_w_` で始まる。

int _yr(Game g, int a) => g.l.startYear + a;
bool _span(Game g, int a, int from, int to) {
  final y = _yr(g, a);
  return y >= from && y <= to;
}

bool _in(Game g, List<String> rs) => rs.contains(g.l.region);
bool _alive(Game g, String n) => g.fa[n]?.alive ?? false;
bool _monk(Game g) => g.hasFlag('priesthood');

/// [ns] のいずれかの家に仕える現役の家臣（大名本人は除く）。
bool _serves(Game g, List<String> ns) =>
    ns.contains(g.l.lord) && g.l.rank >= 1 && g.l.rank < 8 && g.active;

/// 戦に出られる家臣。
bool _soldier(Game g, List<String> ns) =>
    _serves(g, ns) && g.canFight && _alive(g, g.l.lord ?? '');

int _c(int v) => clampInt(v, 0, 100);

void _heal(Game g, int n) {
  g.l.hp = g.l.hp + n > g.l.maxhp ? g.l.maxhp : g.l.hp + n;
}

void _lose(Game g, int n) => g.l.gold = g.l.gold >= n ? g.l.gold - n : 0;

/// [lord] の家に移る。
void _join(Game g, String lord, int rank, int fav) {
  final l = g.l;
  l.lord = lord;
  l.rank = rank < 1 ? 1 : rank;
  if (l.rank > l.maxRank) l.maxRank = l.rank;
  l.fav = fav;
  l.ronin = false;
}

/// 命を賭けた働き。[death] の確率で討死し、生き延びれば功を得る。
String _risk(
  Game g,
  double death,
  String cause,
  String dieText,
  int merit,
  String okText, {
  String kind = 'senshi',
  String? mark,
}) {
  if (g.rng.chance(death)) {
    g.die(cause, kind);
    return dieText;
  }
  g.l.merit += merit;
  g.l.fame += merit ~/ 3;
  if (mark != null) g.mark(mark);
  return okText;
}

