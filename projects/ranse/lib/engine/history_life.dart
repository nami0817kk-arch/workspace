/// 戦の外で出会う史実。
///
/// 子ども（5〜14歳）が見る史実（`h_c_`）と、女・商人・僧など戦に出ない大人が
/// 出会う史実（`h_l_`）。どちらも史実の年代と国にだけ出る。

int _yr(Game g, int a) => g.l.startYear + a;
bool _span(Game g, int a, int from, int to) =>
    _yr(g, a) >= from && _yr(g, a) <= to;
bool _reg(Game g, List<String> rs) => rs.contains(g.l.region);
int _c(int v) => clampInt(v, 0, 100);

bool _merchant(Game g) => g.l.cls.id == 'merchant' || g.hasFlag('way_merchant');
bool _monk(Game g) =>
    g.l.cls.id == 'priest' || g.hasFlag('priesthood') || g.hasFlag('monk');

/// 戦に出ない暮らしの人（身分の低い庶民・商人・僧）。
bool _commoner(Game g) =>
    const [
      'beggar',
      'farmer',
      'fisher',
      'merchant',
      'priest',
    ].contains(g.l.cls.id) &&
    g.l.rank < 3;

void _pay(Game g, int n) => g.l.gold = g.l.gold >= n ? g.l.gold - n : 0;

