/// 僧・尼。
bool _monk(Game g) => g.hasFlag('priesthood');

/// 忍び（里の者・抜けた者。主家に仕えていない）。
bool _nin(Game g) =>
    g.l.rank == 0 && !_monk(g) && (g.l.cls.id == 'ninja' || g.hasFlag('nukenin'));

/// 野に生きる者（野盗・流れ者）。
bool _wild(Game g) => g.l.rank == 0 && !_monk(g) && !_nin(g) && g.hasFlag('way_outlaw');

/// 身分で書き分ける（4回目）: 城主より上・主家に仕える身・それ以外（村や町の者）に、僧・忍び・野の者の文を足せる。
/// 書かなかった身分は「それ以外」の文になる。
T _by6<T>(Game g, T high, T serving, T common, {T? monk, T? ninja, T? outlaw}) {
  if (_high(g)) return high;
  if (_serving(g)) return serving;
  if (_monk(g)) return monk ?? common;
  if (_nin(g)) return ninja ?? common;
  if (_wild(g)) return outlaw ?? common;
  return common;
}

/// 城主より上の人の書き出しを、1回目・2回目の場面にも足すための書き分け（城主より上なら [high]、ほかは [other]）。
T _hi<T>(Game g, T high, T other) => _high(g) ? high : other;

// ---------------------------------------------------------------- 既存の仕組みに掛ける倍率（4回目）

/// 合戦の手柄の倍率（4回目の分。[traitBattleGain] が掛ける）。
/// 左利きは先陣の打ち合いで相手の調子を狂わせ、嫉妬深い人は好敵手がいると励む。
double _battleGain4(Game g, String role) {
  var m = 1.0;
  if (g.has('lefty') && role == 'van') m *= 1.06;
  if (g.has('jealous') && g.l.people.containsKey('好敵手')) m *= 1.06;
  return m;
}

/// 仕入れの旅で当たる見込みに足す値（4回目の分。悪知恵。[traitTradeEdge] が足す）。
double _tradeEdge4(Game g) => g.has('cunning') ? .06 : 0;

/// 仕官の見込みに足す値（4回目の分。国言葉に通じる人は、よその国でもよそ者と見られない。[traitServeEdge] が足す）。
double _serveEdge4(Game g) => g.has('dialects') ? .05 : 0;

/// 自分を狙う刺客を罠にかける見込みに足す値（執念深い。`ways.dart` の刺客の影）。
double traitTrap(Game g) => g.has('vengeful') ? .15 : 0;

/// 夜討ちで、気づかれずに敵陣へ寄れるか（忍び足。`battles.dart` の夜襲を命じられる）。
bool traitNightRaid(Game g) => g.has('stealth');

