import 'game.dart';

/// 何度も起きる岐路（出陣・侵攻・仕入れの旅・獲物・旅路）の書き出しを、回数と時節で書き分ける。
/// 2026-11-23 の実測で、選んだ重点しだいで同じ岐路が1人生に4〜9回出ていたため（回数は選んだ結果なので減らさない）。

int _n(Game g, String tag) => g.l.focus[tag] ?? 0;

String _season(Game g) => g.l.t % 2 == 0
    ? g.rng.pick(['田植えの終わった頃', '若葉の頃', '梅雨の晴れ間'])
    : g.rng.pick(['稲刈りの済んだ頃', '木枯らしの吹く頃', '雪の便りの届く頃']);

String battleIntro(Game g) {
  final n = _n(g, 'war');
  final lord = g.l.lord ?? '主家';
  final head = n <= 2
      ? '主命により、合戦に加わることになった。'
      : g.rng.pick([
          '${_season(g)}、$lord家にまた陣触れが出た。',
          '具足の紐を結ぶ手にも、もう迷いはない。$lord家の陣触れだ。',
          '国境の向こうに、敵の旗が見えたという。$lord家の陣触れに応じる。',
          '戦はいつまで続くのか。それでも、陣触れが出れば行くしかない。',
          '若い者たちが、あなたの顔を見て落ち着きを取り戻す。今度の戦も、主命だ。',
        ]);
  return '$headどの持ち場に就く？';
}

String invadeIntro(Game g) {
  final n = _n(g, 'conquer');
  if (n <= 1) return '初めて、自らの采配で兵を他国へ向ける。どの国を攻める？';
  return g.rng.pick([
    '${_season(g)}、兵糧は整った。どの国に兵を向ける？',
    '軍議の座で、家臣たちがあなたの言葉を待っている。どの国を攻める？',
    '隣国の内紛の噂が届いた。どこを攻める？',
    '天下への道は、まだ遠い。次はどの国に兵を向ける？',
  ]);
}

String tradeIntro(Game g) {
  final n = _n(g, 'journey');
  if (n <= 1) return '初めての仕入れの旅に出る。どこへ行く？';
  return g.rng.pick([
    '${_season(g)}、荷車の支度が整った。どこへ仕入れに出る？',
    '番頭が、今年はどこへ行くかと尋ねてきた。',
    '同業の噂では、遠国の品が値上がりしているという。どこへ仕入れに出る？',
    '帳面を閉じ、旅の支度をした。どこへ行く？',
  ]);
}

String raidIntro(Game g) {
  final n = _n(g, 'prey');
  if (n <= 1) return '街道に、獲物が通りかかった。';
  return g.rng.pick([
    '${_season(g)}、峠の茂みに身を潜めていると、荷を積んだ列が近づいてきた。',
    '仲間の見張りが、口笛で合図を送ってきた。獲物だ。',
    '夜明け前の街道に、松明の列が見える。',
    '腹が減った。今日の獲物を探しに、街道へ下りた。',
  ]);
}

String wanderIntro(Game g) {
  final n = _n(g, 'drift');
  if (n <= 1) return '旅の空の下、どこへ流れていく？';
  return g.rng.pick([
    '${_season(g)}、また草鞋を履き替えた。次はどこへ流れていく？',
    '宿場の囲炉裏端で、遠い国の噂を聞いた。どこへ行く？',
    'ひとところに長くいると、足がうずく。どこへ流れていく？',
    '見知らぬ土地にも、もう慣れた。次はどこへ？',
  ]);
}
