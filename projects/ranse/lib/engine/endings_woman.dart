/// 家を支え続けた静かな一生／戦国の女傑／政略に生きて心を置き去りにした一生、の三つの手触りを持たせる。

double _joy(Game g) => g.avgJoy;
int _r(Game g) => g.l.maxRank;
bool _dead(Game g, String s) => (g.l.dead ?? '').contains(s);
bool _f(Game g, String f) => g.hasFlag(f);
bool _p(Game g, String s) => g.l.path.any((e) => e.contains(s));

/// お産で亡くなった。
bool _birth(Game g) => _dead(g, '産褥');

/// 夫を亡くした（戦で亡くして家を守ると決めた人も含む）。
bool _widow(Game g) =>
    (!g.l.married && g.l.people.containsKey('伴侶')) || _p(g, 'を戦で亡くし');

/// 幼い当主の後見として一国を担った。
bool _regent(Game g) => _p(g, '後見として');

/// 家のための輿入れ（政略結婚）をした。
bool _wed(Game g) => _p(g, '輿入れした');

/// 娘との絆（娘の嫁ぎ先を決めた人生だけ）。
int _musume(Game g) => g.l.people['娘']?.bond ?? -1;

/// 生まれの低い家から上がった。
bool _lowBorn(Game g) =>
    const ['beggar', 'farmer', 'fisher'].contains(g.l.cls.id);

