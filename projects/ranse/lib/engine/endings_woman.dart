/// 奥に仕えて位を得た女（下女〜大局）、武家に嫁いだ妻、女城主、後見として一国を担った女、女大名の最期を、
/// 死に方（天寿・病・お産・戦死・殉死や処刑・毒・奥御殿の火事・飢え・行方知れず）と乱世を生き抜いた era で分け、
