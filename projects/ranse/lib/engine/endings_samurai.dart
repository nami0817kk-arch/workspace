/// 手書きの最期: 足軽・侍（130本）。
/// 主家に仕えて最高位が1〜4（足軽・足軽組頭・馬廻・侍大将）だった人生の最期。
/// 女性で位を得た人は「女の道」に入るので、この道は男の人生だけになる。
/// 戦死を最も厚くし、最高位（`maxRank`）・幸福（`avgJoy`）・足軽の暮らしの旗（乱取り・朋輩・恩賞・字）・
/// 幼い日の旗（戦場を見た・家を背負う・幼なじみ）・史実の合戦（死因の文）・主君にした有名人で書き分ける。

int _r(Game g) => g.l.maxRank;
bool _dead(Game g, String s) => (g.l.dead ?? '').contains(s);
bool _f(Game g, String f) => g.hasFlag(f);
bool _p(Game g, String s) => g.l.path.any((e) => e.contains(s));
bool _has(Game g, String role) => g.l.people.containsKey(role);
bool _lord(Game g, String name) => g.l.people['主君']?.name == name;
bool _lordAlive(Game g, String name) => _lord(g, name) && !personDied(g, name);
bool _family(Game g) => g.l.married && g.l.kids > 0;
bool _ronin(Game g) => _p(g, '足軽をやめた') || _p(g, '出奔') || _p(g, '浪人となった');

